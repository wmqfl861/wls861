#pragma once
#include "wls/store.hpp"
#include <filesystem>

namespace wls::s1 {
// Host-only allocation. Never imports an existing user directory. The worker
// later binds only identity.workspace_identity.path, not the ownership envelope.
Json allocate_owned_workspace(Store& store, const std::string& request_id,
                              const std::string& task_id,
                              const std::filesystem::path& parent,
                              const std::string& idempotency_key);
// Explicit destructive invocation. Frozen cleanup.enabled, exact success
// receipt, completed experience, settled usage and original process exit facts
// are mandatory. max_unlinks bounds a whole invocation, including root removal.
// Missing delivery packages are never regenerated by this routine.
Json cleanup_owned_workspaces(Store& store, const std::string& request_id,
                              std::size_t max_unlinks = 1024);
} // namespace wls::s1
